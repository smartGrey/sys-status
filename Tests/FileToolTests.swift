final class FileToolTests: XCTestCase {
    private func fixture() throws -> URL {
        let url = URL.temporaryDirectory.appendingPathComponent(UUID().uuidString, isDirectory: true)
        try FileManager.default.createDirectory(at: url, withIntermediateDirectories: false)
        addTeardownBlock { try FileManager.default.removeItem(at: url) }
        return url
    }

    @discardableResult
    private func write(_ text: String, _ path: String, in root: URL) throws -> URL {
        let url = root.appendingPathComponent(path)
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try Data(text.utf8).write(to: url)
        return url
    }

    func testProjectFilesAcrossLanguages() throws {
        let root = try fixture()
        let included = ["ui/View.vue": "<template/>", "Sources/入口.swift": "import Foundation",
                        "config/router.unusual": "route = /", "bin/maintain": "#!/bin/sh",
                        "Dockerfile": "FROM scratch", "ops-task.run": "#!/usr/bin/env bash",
                        "docs/说明.md": "# 使用", "go.mod": "module demo"]
        for (path, firstLine) in included { try write(firstLine + "\n\nend", path, in: root) }
        for path in ["node_modules/mod/src/main.ts", "target/index.rs", "网速.app/Contents/Info.plist",
                     "third_party/feature.c", "build/app.js", "pnpm-lock.yaml", "assets/bundle.min.js",
                     "go.sum", "lib/api.pb.go", "config/data.csv", "docs/items.jsonl", "src/unknown.log",
                     ".github/workflows/build.yml", ".local/config.yml", "src/.secret.txt", ".readme.md"] {
            try write("one\ntwo", path, in: root)
        }
        try write("// Code generated by protoc. DO NOT EDIT.\nvalue", "model.go", in: root)
        try write("-- PostgreSQL database dump\nvalue", "backup.sql", in: root)
        try write("unrecognized text", "unclassified.odd", in: root)
        let result = try ProjectLineCount.count(root)
        XCTAssertEqual(result.lines, 3 * included.count)
        XCTAssertEqual(result.issues.count, 0)
        XCTAssertFalse(result.groups.contains { $0.name.hasPrefix(".") })
        XCTAssertThrowsError(try ProjectLineCount.count(root.appendingPathComponent(".readme.md")))
        let subfolder = root.appendingPathComponent("config")
        XCTAssertEqual(try ProjectLineCount.count(subfolder).lines, 3)
        XCTAssertEqual(try ProjectLineCount.count(subfolder.appendingPathComponent("data.csv")).lines, 2)
        XCTAssertEqual(try ProjectLineCount.count(root.appendingPathComponent("pnpm-lock.yaml")).lines, 2)
    }

    func testGitWorkingTreeAndSubdirectory() throws {
        let root = try fixture()
        func git(_ arguments: String...) throws {
            let process = Process()
            process.executableURL = URL(fileURLWithPath: "/usr/bin/git")
            process.arguments = ["-C", root.path] + arguments
            try process.run()
            process.waitUntilExit()
            XCTAssertEqual(process.terminationStatus, 0)
        }
        try git("init", "-q")
        try write("ignored*.swift\n", ".gitignore", in: root)
        try write("tracked\n", "docs/ignored-tracked.swift", in: root)
        try git("add", "-f", "--", "docs/ignored-tracked.swift")
        try write("generated\n", "build/tracked.swift", in: root)
        try git("add", "-f", "--", "build/tracked.swift")
        try write("ignored", "docs/ignored-new.swift", in: root)
        try write("other", "outside.swift", in: root)
        try write("tracked hidden", "docs/.hidden.md", in: root)
        try write("tracked hidden folder", "docs/.local/code.swift", in: root)
        try git("add", "--", "docs/.hidden.md", "docs/.local/code.swift")
        try write("image", "assets/screens/logo.png", in: root)
        try write("a\nb\n", "docs/中文\n特殊.uncommon", in: root)
        let removed = try write("gone", "docs/removed.txt", in: root)
        try git("add", "--", "docs/removed.txt")
        try FileManager.default.removeItem(at: removed)
        try FileManager.default.createSymbolicLink(at: root.appendingPathComponent("docs/link.swift"),
                                                  withDestinationURL: root.appendingPathComponent("outside.swift"))
        let result = try ProjectLineCount.count(root.appendingPathComponent("docs"))
        XCTAssertEqual(result.lines, 3)
        XCTAssertEqual(Dictionary(uniqueKeysWithValues: result.groups.map { ($0.name, $0.lines) }),
                       ["ignored-tracked.swift": 1, "中文\n特殊.uncommon": 2])
        XCTAssertEqual(result.issues.count, 0)
        let repo = try ProjectLineCount.count(root)
        XCTAssertEqual(repo.lines, 4)
        XCTAssertEqual(repo.groups.map(\.name), ["assets", "docs", "outside.swift"])
        XCTAssertEqual(repo.groups[0].children.map(\.name), ["screens"])
        XCTAssertEqual(repo.groups[0].lines, 0)
    }

    func testFileTreeRelativeToSelection() throws {
        let root = try fixture()
        try write("ignored", "src/config/bundle.min.js", in: root)
        try write("image", "相关文件资料/logo.jpg", in: root)
        let noText = try ProjectLineCount.count(root)
        XCTAssertEqual(noText.lines, 0)
        XCTAssertEqual(Set(noText.groups.map(\.name)), ["相关文件资料", "src"])
        XCTAssertEqual(noText.groups.first { $0.name == "src" }?.children.first?.lines, 0)
        for path in ["readme.md", "src/b.swift", "src/ui10/docs/d.txt", "src/ui2/p.md", "src/ui2/d.txt"] {
            try write("a\nb", path, in: root)
        }
        try write("", "docs/empty.md", in: root)
        let result = try ProjectLineCount.count(root)
        XCTAssertEqual(result.lines, 10)
        let visible = result.groups.filter { $0.name != "相关文件资料" }
        XCTAssertEqual(visible.map(\.name), ["docs", "readme.md", "src"])
        XCTAssertEqual(visible.map(\.lines), [0, 2, 8])
        XCTAssertEqual(visible[0].children.map(\.name), ["empty.md"])
        let children = visible[2].children
        XCTAssertEqual(children.map(\.name), ["b.swift", "config", "ui2", "ui10"])
        XCTAssertEqual(children.map(\.lines), [2, 0, 4, 2])
        XCTAssertEqual(children[2].children.map(\.name), ["d.txt", "p.md"])
        XCTAssertEqual(children[3].children.first?.children.first?.name, "d.txt")
        let sub = try ProjectLineCount.count(root.appendingPathComponent("src"))
        XCTAssertEqual(sub.groups.map(\.name), children.map(\.name))
        XCTAssertEqual(sub.groups.map(\.lines), children.map(\.lines))
    }

    func testLineEndingsEncodingsAndBinaryDetection() throws {
        let root = try fixture()
        let url = root.appendingPathComponent("data.csv")
        let samples: [(Data, Int)] = [
            (Data(), 0), (Data("\n\nx".utf8), 3), (Data("x\r\ny\rz\n".utf8), 3),
            (Data(repeating: 97, count: 8191) + Data("\r\nend".utf8), 2),
            (Data([0xef, 0xbb, 0xbf]), 0),
            (Data([0xff, 0xfe]) + "中文\r\n末行".data(using: .utf16LittleEndian)!, 2),
            (Data([0, 0, 0xfe, 0xff]) + "😀\r末行".data(using: .utf32BigEndian)!, 2)
        ]
        for (data, expected) in samples {
            try data.write(to: url)
            XCTAssertEqual(try ProjectLineCount.count(url).lines, expected)
        }
        for data in [Data(repeating: 97, count: 9000) + Data([0]), Data("%PDF-1.4\n".utf8)] {
            try data.write(to: url)
            XCTAssertThrowsError(try ProjectLineCount.count(url))
        }
    }

    func testCleanAppleDoubleAndKeepOriginalsAndLinks() throws {
        let root = try fixture(), outside = try fixture()
        let song = try write("audio", "album/song.flac", in: root)
        var tag: UInt8 = 1
        XCTAssertEqual(setxattr(song.path, "com.example.test", &tag, 1, 0, 0), 0)
        let sidecar = root.appendingPathComponent("album/._song.flac")
        // Ask macOS to produce the AppleDouble sidecar, as on a real transfer.
        XCTAssertEqual(copyfile(song.path, sidecar.path, nil, copyfile_flags_t(COPYFILE_PACK | COPYFILE_METADATA)), 0)
        let ds = try write("view", "album/.DS_Store", in: root)
        let regular = try write("ordinary\n", "album/._notes", in: root)
        let truncated = root.appendingPathComponent("album/._incomplete")
        let header = try XCTUnwrap(try FileHandle(forReadingFrom: sidecar).read(upToCount: 26))
        try header.write(to: truncated)
        let outsideDS = try write("outside", ".DS_Store", in: outside)
        let link = root.appendingPathComponent("mounted")
        try FileManager.default.createSymbolicLink(at: link, withDestinationURL: outside)
        try FileManager.default.createSymbolicLink(at: root.appendingPathComponent("._link"), withDestinationURL: outsideDS)
        let first = try DirectoryFiles.cleanMacFiles(in: root)
        XCTAssertEqual(first.finderRecords, 1)
        XCTAssertEqual(first.appleDoubleFiles, 1)
        XCTAssertEqual(first.total, 2)
        XCTAssertEqual(first.issues.count, 0)
        let repeatRun = try DirectoryFiles.cleanMacFiles(in: root)
        XCTAssertEqual(repeatRun.total, 0)
        XCTAssertEqual(repeatRun.issues.count, 0)
        XCTAssertFalse(FileManager.default.fileExists(atPath: sidecar.path))
        XCTAssertFalse(FileManager.default.fileExists(atPath: ds.path))
        XCTAssertEqual(try String(contentsOf: regular, encoding: .utf8), "ordinary\n")
        XCTAssertEqual(try Data(contentsOf: truncated), header)
        XCTAssertEqual(try String(contentsOf: song, encoding: .utf8), "audio")
        XCTAssertEqual(try String(contentsOf: outsideDS, encoding: .utf8), "outside")
        XCTAssertNotNil(try FileManager.default.destinationOfSymbolicLink(atPath: root.appendingPathComponent("._link").path))
        XCTAssertThrowsError(try DirectoryFiles.cleanMacFiles(in: link))
    }

    func testPartialResultsOnUnreadableDirectory() throws {
        let root = try fixture()
        let blocked = try write("data", "private/info.txt", in: root).deletingLastPathComponent()
        try write("one\ntwo", "readme.md", in: root)
        XCTAssertEqual(chmod(blocked.path, 0), 0)
        defer { chmod(blocked.path, 0o700) }
        try write("", ".DS_Store", in: root)
        guard case .lines(let count) = FileTool.count.run(at: root).content,
              case .cleanup(let clean) = FileTool.clean.run(at: root).content else {
            return XCTFail("Expected partial results")
        }
        XCTAssertEqual(count.lines, 2)
        XCTAssertEqual(count.groups.map(\.lines), [0, 2])
        XCTAssertEqual(clean.total, 1)
        XCTAssertEqual(clean.issues.count, 1)
        XCTAssertTrue(clean.issues.first?.contains("private") == true)
        XCTAssertTrue(count.issues.first?.contains("private") == true)
    }

    @MainActor func testMenuActionsSelectionCancellationAndResults() async throws {
        _ = NSApplication.shared
        let root = try fixture()
        let file = try write("a\nb", "data.csv", in: root)
        let ds = try write("", ".DS_Store", in: root)
        for tool in FileTool.allCases {
            let panel = tool.selectionPanel()
            XCTAssertTrue(panel.canChooseDirectories)
            XCTAssertEqual(panel.canChooseFiles, tool == .count)
            XCTAssertFalse(panel.allowsMultipleSelection)
            XCTAssertEqual(panel.prompt, tool == .count ? "统计" : "清理")
        }
        let menu = NSMenu()
        menu.autoenablesItems = false
        var selection: URL?
        var messages: [FileTool.Message] = []
        let tools = FileToolsMenu(select: { _, _ in selection }, present: { messages.append($0) })
        tools.add(to: menu)
        XCTAssertEqual(menu.items.map(\.title), ["统计文本行数", "清理 Mac 附加文件"])
        func click(_ index: Int) async throws {
            menu.performActionForItem(at: index)
            XCTAssertTrue(menu.items.allSatisfy { !$0.isEnabled })
            let deadline = ContinuousClock.now + .seconds(3)
            while !menu.items[0].isEnabled && ContinuousClock.now < deadline {
                try await Task.sleep(for: .milliseconds(5))
            }
            XCTAssertTrue(menu.items.allSatisfy(\.isEnabled))
        }
        try await click(1)
        XCTAssertTrue(messages.isEmpty)
        XCTAssertTrue(FileManager.default.fileExists(atPath: ds.path))
        selection = file
        try await click(0)
        guard case .lines(let count) = messages.last?.content else { return XCTFail("Expected a line count") }
        XCTAssertEqual(count.lines, 2)
        XCTAssertTrue(count.groups.isEmpty)
        selection = root
        try await click(1)
        guard case .cleanup(let clean) = messages.last?.content else { return XCTFail("Expected a cleanup result") }
        XCTAssertEqual(clean.total, 1)
        XCTAssertFalse(FileManager.default.fileExists(atPath: ds.path))
    }

    @MainActor func testResultPanelSelectionsFromMenu() async throws {
        let app = NSApplication.shared
        let root = try fixture()
        try write("root", "readme.md", in: root)
        try write("one\ntwo", "src/a.swift", in: root)
        try write("three\nfour\nfive", "src/ui/deep/b.swift", in: root)
        try write("", "src/zero/a.swift", in: root)
        let longName = String(repeating: "很长的目录名称", count: 6)
        try write("doc", longName + "/readme.md", in: root)
        let menu = NSMenu()
        menu.autoenablesItems = false
        var selection: URL? = root
        var pickerRequests: [(FileTool, URL?)] = []
        let tools = FileToolsMenu(select: { tool, directory in
            pickerRequests.append((tool, directory))
            return selection
        })
        tools.add(to: menu)
        func descendants(_ view: NSView) -> [NSView] { [view] + view.subviews.flatMap(descendants) }
        func waitForResult() async throws -> FileToolResultPanel {
            let deadline = ContinuousClock.now + .seconds(5)
            while !menu.items[0].isEnabled && ContinuousClock.now < deadline {
                try await Task.sleep(for: .milliseconds(10))
            }
            return try XCTUnwrap(app.windows.compactMap { $0 as? FileToolResultPanel }.first(where: \.isVisible))
        }
        func reselect(_ panel: FileToolResultPanel) throws -> NSButton {
            try XCTUnwrap(panel.titlebarAccessoryViewControllers.flatMap { descendants($0.view) }
                .compactMap { $0 as? NSButton }.first { $0.title == "重新选择" })
        }
        menu.performActionForItem(at: 0)
        let panel = try await waitForResult()
        let content = try XCTUnwrap(panel.contentView)
        XCTAssertTrue(panel.styleMask.contains(.resizable))
        XCTAssertGreaterThanOrEqual(try reselect(panel).frame.width, try reselect(panel).intrinsicContentSize.width)
        func button(_ title: String) throws -> NSButton {
            try XCTUnwrap(descendants(content).compactMap { $0 as? NSButton }.first { $0.title == title })
        }
        func hasText(_ value: String) -> Bool {
            descendants(content).contains { ($0 as? NSTextField)?.stringValue == value }
        }
        let disclosure = try button("目录详情")
        XCTAssertEqual(disclosure.state, .off)
        XCTAssertTrue(hasText("7"))
        disclosure.performClick(nil)
        let outline = try XCTUnwrap(descendants(content).compactMap { $0 as? NSOutlineView }.first)
        XCTAssertEqual(outline.numberOfRows, 3)
        let parentIndex = try XCTUnwrap((0..<outline.numberOfRows).first { (outline.item(atRow: $0) as? LineGroup)?.name == "src" })
        let parent = try XCTUnwrap(outline.item(atRow: parentIndex) as? LineGroup)
        outline.selectRowIndexes([parentIndex], byExtendingSelection: false)
        panel.makeFirstResponder(outline)
        func press(_ code: UInt16, _ characters: String) throws {
            let key = try XCTUnwrap(NSEvent.keyEvent(with: .keyDown, location: .zero, modifierFlags: [],
                timestamp: 0, windowNumber: panel.windowNumber, context: nil, characters: characters,
                charactersIgnoringModifiers: characters, isARepeat: false, keyCode: code))
            outline.keyDown(with: key)
        }
        try press(124, "\u{f703}")
        XCTAssertTrue(outline.isItemExpanded(parent))
        XCTAssertEqual(outline.numberOfRows, 6)
        func checkbox(_ name: String) throws -> NSButton {
            let row = try XCTUnwrap((0..<outline.numberOfRows).first { (outline.item(atRow: $0) as? LineGroup)?.name == name })
            return try XCTUnwrap(outline.view(atColumn: 0, row: row, makeIfNecessary: true) as? NSButton)
        }
        let ui = try XCTUnwrap(parent.children.first { $0.name == "ui" })
        outline.expandItem(ui)
        let deep = try XCTUnwrap(ui.children.first)
        outline.expandItem(deep)
        try checkbox("b.swift").performClick(nil)
        XCTAssertEqual(try checkbox("ui").state, .off)
        XCTAssertTrue(hasText("4"))
        XCTAssertTrue(hasText("已选行数"))
        XCTAssertEqual(try checkbox("src").state, .mixed)
        try checkbox("src").performClick(nil)
        XCTAssertTrue(hasText("7"))
        XCTAssertEqual(try checkbox("ui").state, .on)
        try press(49, " ")
        XCTAssertTrue(hasText("2"))
        XCTAssertEqual(try checkbox("a.swift").state, .off)
        try button("取消全选").performClick(nil)
        XCTAssertTrue(hasText("已选行数"))
        XCTAssertFalse(try button("取消全选").isEnabled)
        XCTAssertEqual(try checkbox("readme.md").state, .off)
        disclosure.performClick(nil)
        XCTAssertTrue(hasText("0"))
        disclosure.performClick(nil)
        XCTAssertEqual(try checkbox("src").state, .off)
        try button("全选").performClick(nil)
        XCTAssertTrue(hasText("7"))
        XCTAssertEqual(try checkbox(longName).toolTip, longName)
        let scroll = try XCTUnwrap(outline.enclosingScrollView)
        content.layoutSubtreeIfNeeded()
        let originalWidth = outline.tableColumns[0].width
        let originalHeight = scroll.frame.height
        tools.windowWillStartLiveResize(Notification(name: NSWindow.willStartLiveResizeNotification, object: panel))
        let originalSize = content.bounds.size
        let newSize = NSSize(width: originalSize.width + 180, height: originalSize.height + 100)
        panel.setContentSize(newSize)
        content.layoutSubtreeIfNeeded()
        XCTAssertGreaterThan(outline.tableColumns[0].width, originalWidth + 100)
        XCTAssertGreaterThan(scroll.frame.height, originalHeight + 80)
        disclosure.performClick(nil)
        disclosure.performClick(nil)
        XCTAssertEqual(content.bounds.size, newSize)
        try button("取消全选").performClick(nil)
        selection = nil
        try reselect(panel).performClick(nil)
        let cancelled = try await waitForResult()
        XCTAssertTrue(cancelled === panel)
        XCTAssertTrue(hasText("0"))
        XCTAssertEqual(pickerRequests.last?.0, .count)
        XCTAssertEqual(pickerRequests.last?.1, root.deletingLastPathComponent())
        selection = root
        try reselect(panel).performClick(nil)
        let next = try await waitForResult()
        XCTAssertFalse(panel.isVisible)
        let nextViews = descendants(try XCTUnwrap(next.contentView))
        XCTAssertEqual(nextViews.compactMap { $0 as? NSButton }.first { $0.title == "目录详情" }?.state, .off)
        XCTAssertTrue(nextViews.contains { ($0 as? NSTextField)?.stringValue == "7" })
        menu.performActionForItem(at: 1)
        let emptyCleanup = try await waitForResult()
        XCTAssertTrue(emptyCleanup.styleMask.contains(.resizable))
        XCTAssertEqual(try reselect(emptyCleanup).title, "重新选择")
        XCTAssertTrue(descendants(try XCTUnwrap(emptyCleanup.contentView)).contains {
            ($0 as? NSTextField)?.stringValue == "未发现可清理的 Mac 附加文件"
        })
        let cleanupTarget = try fixture()
        let removable = try write("", ".DS_Store", in: cleanupTarget)
        selection = cleanupTarget
        try reselect(emptyCleanup).performClick(nil)
        let cleaned = try await waitForResult()
        defer { cleaned.close() }
        XCTAssertFalse(emptyCleanup.isVisible)
        XCTAssertEqual(pickerRequests.last?.0, .clean)
        XCTAssertEqual(pickerRequests.last?.1, root.deletingLastPathComponent())
        XCTAssertFalse(FileManager.default.fileExists(atPath: removable.path))
    }

    @MainActor func testBothMenuActionsOpenTheNativePicker() async throws {
        let app = NSApplication.shared
        let menu = NSMenu()
        menu.autoenablesItems = false
        let tools = FileToolsMenu(present: { _ in XCTFail("Cancelling the picker should show no result.") })
        tools.add(to: menu)

        func waitUntil(_ condition: () -> Bool) async throws {
            let deadline = ContinuousClock.now + .seconds(5)
            while !condition() && ContinuousClock.now < deadline {
                try await Task.sleep(for: .milliseconds(20))
            }
        }

        for (index, tool) in FileTool.allCases.enumerated() {
            menu.performActionForItem(at: index)
            try await waitUntil { app.windows.contains { $0 is NSOpenPanel && $0.isVisible } }
            guard let panel = app.windows.first(where: { $0 is NSOpenPanel && $0.isVisible }) as? NSOpenPanel else {
                XCTFail("The native picker did not open for \(tool.title).")
                return
            }
            XCTAssertEqual(panel.title, tool.title)
            XCTAssertEqual(panel.canChooseFiles, tool == .count)
            panel.cancel(nil)
            try await waitUntil { menu.items[index].isEnabled }
            XCTAssertTrue(menu.items[index].isEnabled)
        }
    }
